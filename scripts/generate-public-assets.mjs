import { mkdirSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const publicDir = path.join(rootDir, 'public');
const outputFile = path.join(rootDir, 'generated', 'publicAssets.ts');
const imageExtensions = new Set(['.gif', '.jpeg', '.jpg', '.png', '.svg', '.webp']);

const listPublicImages = (relativeDir) => {
  const absoluteDir = path.join(publicDir, relativeDir);

  try {
    return readdirSync(absoluteDir, { withFileTypes: true })
      .filter((entry) => entry.isFile() && imageExtensions.has(path.extname(entry.name).toLowerCase()))
      .map((entry) => `${relativeDir}/${entry.name}`)
      .sort((a, b) => a.localeCompare(b, 'pt-BR', { numeric: true, sensitivity: 'base' }));
  } catch (error) {
    if (error && error.code === 'ENOENT') {
      return [];
    }

    throw error;
  }
};

const formatArray = (items) => {
  if (items.length === 0) {
    return '[]';
  }

  return `[\n${items.map((item) => `  ${JSON.stringify(item)},`).join('\n')}\n]`;
};

const content = `// This file is generated by scripts/generate-public-assets.mjs.
// Run npm run generate:public-assets after adding or removing public assets.

export const HERO_IMAGE_FILES = ${formatArray(listPublicImages('hero/banner-hero'))} as const;

export const SPONSOR_SOY_FILES = ${formatArray(listPublicImages('patrocinadores-soja'))} as const;

export const SPONSOR_COTTON_FILES = ${formatArray(listPublicImages('patrocinadores-algodao'))} as const;
`;

mkdirSync(path.dirname(outputFile), { recursive: true });
writeFileSync(outputFile, content);

console.log(`Generated ${path.relative(rootDir, outputFile).replaceAll(path.sep, '/')}`);
